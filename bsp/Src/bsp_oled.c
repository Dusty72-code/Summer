#include "bsp_oled.h"
#include "i2c.h"

static uint8_t oled_buf[OLED_WIDTH * OLED_PAGES];
static uint8_t g_oled_i2c_err_cnt = 0U;

static HAL_StatusTypeDef oled_i2c_safe_write(uint8_t *pdata, uint16_t size) {
    HAL_StatusTypeDef status = HAL_I2C_Master_Transmit(
        &OLED_I2C_HANDLE, OLED_I2C_ADDR, pdata, size, 20);
    if (status != HAL_OK) {
        g_oled_i2c_err_cnt++;
        if (g_oled_i2c_err_cnt > 5U) {
            HAL_I2C_DeInit(&OLED_I2C_HANDLE);
            MX_I2C1_Init();
            g_oled_i2c_err_cnt = 0U;
        }
    } else {
        g_oled_i2c_err_cnt = 0U;
    }
    return status;
}

static void oled_write_cmd(uint8_t cmd) {
    uint8_t data[2] = { 0x00, cmd };
    oled_i2c_safe_write(data, 2);
}

static void oled_write_data(uint8_t val) {
    uint8_t data[2] = { 0x40, val };
    oled_i2c_safe_write(data, 2);
}

void BSP_OLED_Init(void) {
    oled_write_cmd(0xAE);
    oled_write_cmd(0x00); oled_write_cmd(0x10);
    oled_write_cmd(0x40);
    oled_write_cmd(0x81); oled_write_cmd(0xCF);
    oled_write_cmd(0xA1);
    oled_write_cmd(0xC8);
    oled_write_cmd(0xA6);
    oled_write_cmd(0xA8); oled_write_cmd(0x3F);
    oled_write_cmd(0xD3); oled_write_cmd(0x00);
    oled_write_cmd(0xD5); oled_write_cmd(0x80);
    oled_write_cmd(0xD9); oled_write_cmd(0xF1);
    oled_write_cmd(0xDA); oled_write_cmd(0x12);
    oled_write_cmd(0xDB); oled_write_cmd(0x40);
    oled_write_cmd(0x8D); oled_write_cmd(0x14);
    oled_write_cmd(0xAF);
    BSP_OLED_Clear();
    BSP_OLED_Refresh();
}

void BSP_OLED_Clear(void) {
    memset(oled_buf, 0x00, sizeof(oled_buf));
}

void BSP_OLED_Refresh(void) {
    for (uint8_t page = 0; page < OLED_PAGES; page++) {
        oled_write_cmd(0xB0 + page);
        oled_write_cmd(0x00);
        oled_write_cmd(0x10);
        for (uint8_t col = 0; col < OLED_WIDTH; col++) {
            oled_write_data(oled_buf[page * OLED_WIDTH + col]);
        }
    }
}

